CREATE TABLE IF NOT EXISTS eco_users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, store VARCHAR(2) NOT NULL,
 name VARCHAR(120) NOT NULL,email VARCHAR(190) NOT NULL,pw VARCHAR(255) NOT NULL,
 role VARCHAR(16) NOT NULL DEFAULT 'cliente',created INT UNSIGNED NOT NULL,
 UNIQUE KEY store_email(store,email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS eco_products (
 store VARCHAR(2) NOT NULL,id VARCHAR(60) NOT NULL,data LONGTEXT NOT NULL,
 sort_order INT NOT NULL DEFAULT 0,PRIMARY KEY(store,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS eco_orders (
 id VARCHAR(40) PRIMARY KEY,store VARCHAR(2) NOT NULL,user_id INT UNSIGNED NOT NULL,
 data LONGTEXT NOT NULL,total DECIMAL(12,2) NOT NULL,status VARCHAR(80) NOT NULL,
 created INT UNSIGNED NOT NULL, KEY store_user(store,user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS eco_messages (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, store VARCHAR(2) NOT NULL,
 name VARCHAR(120) NOT NULL,email VARCHAR(190) NOT NULL,phone VARCHAR(60) NOT NULL,
 message TEXT NOT NULL,created INT UNSIGNED NOT NULL,KEY store_created(store,created)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS eco_auth_limits (
 bucket CHAR(64) PRIMARY KEY,attempts INT UNSIGNED NOT NULL,expires INT UNSIGNED NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS eco_reviews (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,store VARCHAR(2) NOT NULL,
 product_id VARCHAR(60) NOT NULL,user_id INT UNSIGNED NOT NULL,
 rating INT NOT NULL,review TEXT NOT NULL,created INT UNSIGNED NOT NULL,
 UNIQUE KEY product_user(store,product_id,user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
